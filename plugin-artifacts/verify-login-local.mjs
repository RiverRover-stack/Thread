import assert from 'node:assert/strict';
const base='http://127.0.0.1:3100';
const request=(path,options={})=>fetch(base+path,{...options,redirect:'manual'});
assert.equal((await request('/')).status,307);
const page=await request('/login'); assert.equal(page.status,200);
assert.ok((await page.text()).includes('Welcome to Thread'));
const form=(password)=>request('/api/auth/login',{method:'POST',headers:{origin:'https://127.0.0.1:3100','content-type':'application/x-www-form-urlencoded'},body:new URLSearchParams({password})});
const wrong=await form('wrong');assert.equal(wrong.status,303);assert.equal(wrong.headers.get('set-cookie'),null);
const login=await form('synthetic-login-http-password');assert.equal(login.status,303);
const cookie=login.headers.get('set-cookie').split(';')[0];
assert.match(cookie,/^__Host-thread-session=/);
const home=await request('/',{headers:{cookie}});assert.equal(home.status,200);
const html=await home.text();assert.ok(html.includes('Sign out'));assert.ok(html.includes('Google-hosted Gemma interprets the transcript.'));
assert.ok(!html.includes('synthetic-login-http-password'));
assert.equal((await request('/api/process',{method:'POST',headers:{cookie,origin:'https://127.0.0.1:3100'}})).status,415);
assert.equal((await request('/api/process',{method:'POST',headers:{cookie,origin:'https://evil.example'}})).status,403);
const logout=await request('/api/auth/logout',{method:'POST',headers:{cookie,origin:'https://127.0.0.1:3100'}});assert.equal(logout.status,303);assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
assert.equal((await request('/thoughts')).status,307);
console.log('Production HTTP login, wrong password, signed cookie, authenticated HTML/API, provider label, logout, and cross-site rejection passed.');
